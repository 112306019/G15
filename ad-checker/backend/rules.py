def _resolve_law_ref(group: dict, category: str) -> str:
    """law_ref 可能是字串或依類別對應的 dict。"""
    ref = group.get("law_ref", "")
    if isinstance(ref, dict):
        return ref.get(category, "")
    return ref


def detect_violations(text: str, category: str) -> list[dict]:
    """
    Rule-based 違規詞檢測。
    只套用「所選產品類別」適用的規則群組，確保不會以無關類別的法規誤判。
    """
    violations = []
    seen = set()

    for group in PROHIBITED_GROUPS:
        if category not in group.get("categories", ALL_CATEGORIES):
            continue  # 此規則不適用目前選擇的產品類別 → 跳過

        law_ref = _resolve_law_ref(group, category)
        for word in group["words"]:
            if word in text and word not in seen:
                seen.add(word)
                violations.append({
                    "word": word,
                    "label": group["label"],
                    "severity": group["severity"],
                    "group": group["key"],
                    "law_ref": law_ref,
                })

    return violations


def applicable_groups(category: str) -> list[dict]:
    """回傳某類別適用的規則群組摘要（供 /api/rules 或除錯用）。"""
    out = []
    for g in PROHIBITED_GROUPS:
        if category in g.get("categories", ALL_CATEGORIES):
            out.append({
                "key": g["key"],
                "label": g["label"],
                "severity": g["severity"],
                "law_ref": _resolve_law_ref(g, category),
                "word_count": len(g["words"]),
            })
    return out
